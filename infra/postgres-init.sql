DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'alyvo_app') THEN
    CREATE ROLE alyvo_app LOGIN PASSWORD 'alyvo-app';
  ELSE
    ALTER ROLE alyvo_app WITH LOGIN PASSWORD 'alyvo-app' NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
  END IF;
END
$$;

GRANT CONNECT ON DATABASE alyvo TO alyvo_app;
GRANT USAGE ON SCHEMA public TO alyvo_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO alyvo_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO alyvo_app;
ALTER DEFAULT PRIVILEGES FOR ROLE alyvo IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO alyvo_app;
ALTER DEFAULT PRIVILEGES FOR ROLE alyvo IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO alyvo_app;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
